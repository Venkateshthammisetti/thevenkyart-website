/**
 * Builds the Student Gallery on students.html from data/student-gallery.json.
 *
 * USAGE:
 *   node build-student-gallery.js "<folder with the original student photos>"
 *   node build-student-gallery.js "<folder>" --html-only   → skip image encoding, just rewrite the HTML
 *
 * WHAT IT DOES:
 *   - Checks every photo in the folder is listed in the manifest exactly once (and vice versa)
 *   - Applies EXIF rotation, trims screen UI using each item's `crop`, strips all
 *     metadata (GPS, device info) and writes two WebP sizes per photo to
 *     assets/images/student-gallery/<category>/: <slug>-sm.webp (grid) and <slug>-lg.webp (lightbox)
 *   - Rewrites the gallery markup in students.html between the STUDENT-GALLERY markers
 *     and refreshes every data-sg-count="<category|all>" number on the page
 */

const path = require("path");
const fs = require("fs");

let sharp;
try {
  sharp = require("sharp");
} catch {
  console.error("\nERROR: sharp is not installed.\nRun: npm install sharp\n");
  process.exit(1);
}

const ROOT = __dirname;
const MANIFEST = path.join(ROOT, "data", "student-gallery.json");
const PAGE = path.join(ROOT, "students.html");
const OUT_DIR = path.join(ROOT, "assets", "images", "student-gallery");
const OUT_URL = "assets/images/student-gallery";

const SMALL_BOX = { width: 800, height: 640 }; // grid tiles (row height ≤ ~300 CSS px at 2x)
const LARGE_BOX = { width: 1800, height: 1800 }; // lightbox
const QUALITY = { small: 74, large: 80 };
const SUPPORTED = /\.(jpe?g|png)$/i;
const START = "<!-- STUDENT-GALLERY:START (generated by build-student-gallery.js — edit data/student-gallery.json instead) -->";
const END = "<!-- STUDENT-GALLERY:END -->";

const args = process.argv.slice(2);
const SRC_DIR = args.find((a) => !a.startsWith("--"));
const HTML_ONLY = args.includes("--html-only");

if (!SRC_DIR || !fs.existsSync(SRC_DIR)) {
  console.error('\nUsage: node build-student-gallery.js "<folder with the original photos>"\n');
  process.exit(1);
}

function listPhotos(dir, base = dir, list = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) listPhotos(full, base, list);
    else if (SUPPORTED.test(entry.name)) list.push(path.relative(base, full).split(path.sep).join("/"));
  }
  return list;
}

function slugify(text) {
  return text
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function escapeHtml(text) {
  return String(text)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function checkManifest(manifest) {
  const onDisk = new Set(listPhotos(SRC_DIR));
  const seen = new Set();
  const problems = [];

  for (const item of manifest.items) {
    if (seen.has(item.src)) problems.push(`listed twice: ${item.src}`);
    seen.add(item.src);
    if (!onDisk.has(item.src)) problems.push(`not found in folder: ${item.src}`);
    if (item.skip) continue;
    if (!manifest.categories[item.cat]) problems.push(`unknown cat "${item.cat}": ${item.src}`);
    if (!item.title || !item.alt) problems.push(`missing title/alt: ${item.src}`);
  }
  for (const file of onDisk) {
    if (!seen.has(file)) problems.push(`in folder but not in manifest: ${file}`);
  }
  if (problems.length) {
    console.error("\nManifest problems:\n  " + problems.join("\n  ") + "\n");
    process.exit(1);
  }
}

async function encode(item, slug) {
  const dir = path.join(OUT_DIR, item.cat);
  const small = path.join(dir, `${slug}-sm.webp`);
  const large = path.join(dir, `${slug}-lg.webp`);

  if (HTML_ONLY) {
    const meta = await sharp(small).metadata();
    return { width: meta.width, height: meta.height, bytes: 0 };
  }

  fs.mkdirSync(dir, { recursive: true });

  // Rotate first so crop fractions match the photo as it is seen
  let base = sharp(path.join(SRC_DIR, item.src)).rotate();
  if (item.crop) {
    const { data, info } = await base.toBuffer({ resolveWithObject: true });
    const [l, t, r, b] = item.crop;
    base = sharp(data).extract({
      left: Math.round(info.width * l),
      top: Math.round(info.height * t),
      width: Math.round(info.width * (r - l)),
      height: Math.round(info.height * (b - t)),
    });
  }
  const buffer = await base.toBuffer();

  const smallInfo = await sharp(buffer)
    .resize({ ...SMALL_BOX, fit: "inside", withoutEnlargement: true })
    .webp({ quality: QUALITY.small, effort: 5 })
    .toFile(small);
  const largeInfo = await sharp(buffer)
    .resize({ ...LARGE_BOX, fit: "inside", withoutEnlargement: true })
    .webp({ quality: QUALITY.large, effort: 5 })
    .toFile(large);

  return { width: smallInfo.width, height: smallInfo.height, bytes: smallInfo.size + largeInfo.size };
}

function renderItem(item, slug, size, index, categories) {
  const sm = `${OUT_URL}/${item.cat}/${slug}-sm.webp`;
  const lg = `${OUT_URL}/${item.cat}/${slug}-lg.webp`;
  const ratio = (size.width / size.height).toFixed(3);
  const eager = index < 6;
  const student = item.student ? ` data-student="${escapeHtml(item.student)}"` : "";
  return `            <figure class="sg-item" data-cat="${item.cat}" style="--r:${ratio}">
              <a class="sg-link" href="${lg}" data-title="${escapeHtml(item.title)}"${student}>
                <img src="${sm}" width="${size.width}" height="${size.height}" alt="${escapeHtml(item.alt)}"${eager ? "" : ' loading="lazy"'} decoding="async">
              </a>
              <figcaption><span class="sg-title">${escapeHtml(item.title)}</span><span class="sg-cat">${escapeHtml(categories[item.cat].label)}</span></figcaption>
            </figure>`;
}

async function main() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  checkManifest(manifest);

  const items = manifest.items.filter((i) => !i.skip);
  const usedSlugs = new Set();
  const rendered = [];
  const counts = { all: items.length };
  let totalBytes = 0;

  console.log(`\nStudent gallery: ${items.length} photos (${manifest.items.length - items.length} skipped)\n`);

  for (const [index, item] of items.entries()) {
    let slug = slugify(item.title);
    for (let n = 2; usedSlugs.has(`${item.cat}/${slug}`); n++) slug = `${slugify(item.title)}-${n}`;
    usedSlugs.add(`${item.cat}/${slug}`);

    const size = await encode(item, slug);
    totalBytes += size.bytes;
    counts[item.cat] = (counts[item.cat] || 0) + 1;
    rendered.push(renderItem(item, slug, size, index, manifest.categories));
    console.log(`  ✓ ${item.cat}/${slug}`);
  }

  let html = fs.readFileSync(PAGE, "utf8");
  const startAt = html.indexOf(START);
  const endAt = html.indexOf(END);
  if (startAt === -1 || endAt === -1) {
    console.error(`\nCould not find the STUDENT-GALLERY markers in students.html\n`);
    process.exit(1);
  }
  html = html.slice(0, startAt + START.length) + "\n" + rendered.join("\n") + "\n            " + html.slice(endAt);
  html = html.replace(/(data-sg-count="([a-z]+)"[^>]*>)\d*(<)/g, (m, open, cat, close) => `${open}${counts[cat] || 0}${close}`);
  fs.writeFileSync(PAGE, html);

  console.log(`\nCounts: ${JSON.stringify(counts)}`);
  if (!HTML_ONLY) console.log(`Images written: ${(totalBytes / 1024 / 1024).toFixed(1)} MB in ${path.relative(ROOT, OUT_DIR)}/`);
  console.log(`students.html updated.\n`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
